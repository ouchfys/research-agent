import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { build } from "esbuild";
import { pathToFileURL } from "node:url";
import { projectRoot, qaRoot } from "./workspace.mjs";
const verificationRoot = qaRoot;
const root = path.join(verificationRoot, `ingestion-verification-${randomUUID()}`);
mkdirSync(root, { recursive: true });
const output = path.join(root, "store.mjs");
await build({ entryPoints: [path.join(projectRoot, "src/server/store.ts")], outfile: output, bundle: true, platform: "node", format: "esm", target: "node22", logLevel: "silent" });
const { Store } = await import(pathToFileURL(output).href);
const store = new Store(path.join(root, "library"));
let conflictStore;
try {
  const first = store.createTask("第一批资料", [], "collection", "ingestion");
  const second = store.createTask("第二批资料", [], "collection", "ingestion");
  assert.notEqual(first.id, second.id);
  assert.equal(second.sessionFile, void 0);
  store.updateTask(first.id, { status: "paused" });
  store.updateTask(second.id, { status: "paused" });
  const raw = (text, status) => store.putRaw({ id: randomUUID(), taskId: first.id, kind: "web", title: "测试材料", text, status, coverage: "测试来源", createdAt: (/* @__PURE__ */ new Date()).toISOString(), metadata: { inputRole: "input" } });
  const complete = raw("已完成正文", "available"), failed = raw("", "unavailable"), readable = raw("已经识别的图文内容", "partial"), untouched = raw("稍后处理", "available");
  store.ensureTaskInputs(first.id);
  store.recordInputOutcomes(first.id, [
    { inputId: complete.id, status: "answered", reason: "已完成" },
    { inputId: failed.id, status: "blocked", reason: "下载失败" },
    { inputId: readable.id, status: "blocked", reason: "模型余额不足" }
  ]);
  const session = path.join(store.dataDir, "sessions", "old-session.jsonl");
  writeFileSync(session, "saved conversation");
  store.updateTask(first.id, { sessionFile: session });
  store.prepareInputRetry(first.id, [failed.id, readable.id]);
  assert.deepEqual(store.task(first.id).retrySourceIds, [failed.id]);
  assert.deepEqual(store.task(first.id).retryInputIds, [failed.id, readable.id]);
  assert.equal(store.task(first.id).sessionFile, void 0);
  assert.deepEqual(store.task(first.id).previousSessionFiles, [session]);
  assert.equal(store.taskInputs(first.id).find((input) => input.id === complete.id)?.status, "answered");
  assert.throws(() => store.recordInputOutcomes(first.id, [{ inputId: untouched.id, status: "skipped", reason: "不应处理" }]), /所选|选择/);
  assert.throws(() => store.prepareInputRetry(first.id, [complete.id]), /只能重试/);
  assert.deepEqual(store.tasks().find((task) => task.id === first.id)?.inputSummary, { total: 4, published: 0, blocked: 0, pending: 3 });
  const categoryId = store.categories()[0].id;
  let doc = store.saveManual({ categoryId, title: "需要保留的文档", description: "清理对话不清理知识", body: "第一版知识正文", expectedVersion: 0, sources: [{ id: complete.id, title: "真实来源", kind: complete.kind, coverage: complete.coverage, accessedAt: complete.createdAt }] });
  doc = store.saveManual({ ...doc, body: "第二版知识正文", expectedVersion: doc.version });
  const versions = JSON.stringify(store.versions(doc.id)), source = JSON.stringify(store.raw(complete.id));
  const docFile = path.join(store.dataDir, "library", `${doc.id}.md`);
  const unrelatedDraftId = randomUUID();
  const unrelatedDraft = { ...doc, draftId: unrelatedDraftId, taskId: first.id, baseVersion: doc.version, revision: 1, status: "draft" };
  const fixtures = new DatabaseSync(path.join(store.dataDir, "app.sqlite"));
  fixtures.prepare("INSERT INTO records(kind,id,value) VALUES(?,?,?)").run("draft", unrelatedDraftId, JSON.stringify(unrelatedDraft));
  fixtures.close();
  const draftMarkdown = path.join(store.dataDir, "drafts", `${unrelatedDraftId}.md`);
  writeFileSync(draftMarkdown, "未发布草稿正文");
  writeFileSync(path.join(store.dataDir, "drafts", `${unrelatedDraftId}.json`), JSON.stringify(unrelatedDraft));
  const beforeRejectedRetry = JSON.stringify(store.task(first.id));
  assert.throws(() => store.prepareInputRetry(first.id, [failed.id]), /其他未完成草稿/);
  assert.equal(JSON.stringify(store.task(first.id)), beforeRejectedRetry);
  const external = path.join(root, "outside");
  mkdirSync(external);
  const externalSession = path.join(external, "outside.jsonl");
  writeFileSync(externalSession, "external conversation must survive");
  const junction = path.join(store.dataDir, "sessions", "external-junction");
  symlinkSync(external, junction, process.platform === "win32" ? "junction" : "dir");
  store.updateTask(second.id, { sessionFile: docFile, previousSessionFiles: [externalSession, path.join(junction, "outside.jsonl")] });
  store.addMessage(first.id, "user", "原来的聊天");
  store.addMessage(second.id, "assistant", "旧的回答");
  writeFileSync(path.join(store.dataDir, "raw", `pending-${first.id}.json`), '{"test":true}');
  const result = store.clearHistory();
  assert.equal(result.deletedTasks, 2);
  assert.equal(result.deletedMessages, 2);
  assert.equal(store.tasks().length, 0);
  assert.ok(result.backupPath);
  assert.equal(store.document(doc.id).body, "第二版知识正文");
  assert.equal(JSON.stringify(store.versions(doc.id)), versions);
  assert.equal(JSON.stringify(store.raw(complete.id)), source);
  assert.ok(existsSync(docFile));
  assert.ok(existsSync(externalSession));
  assert.ok(!existsSync(session));
  assert.ok(!existsSync(draftMarkdown));
  assert.equal(result.retainedFiles?.length, 3);
  const backup = new DatabaseSync(path.join(result.backupPath, "app.sqlite"), { readOnly: true });
  assert.equal(backup.prepare("SELECT COUNT(*) AS total FROM records WHERE kind='task'").get().total, 2);
  backup.close();
  assert.equal(readFileSync(path.join(result.backupPath, "files", "sessions", "old-session.jsonl"), "utf8"), "saved conversation");
  assert.equal(readFileSync(path.join(result.backupPath, "files", "drafts", `${unrelatedDraftId}.md`), "utf8"), "未发布草稿正文");
  assert.equal(JSON.parse(readFileSync(path.join(result.backupPath, "manifest.json"), "utf8")).status, "cleared");
  conflictStore = new Store(path.join(root, "conflict-library"));
  const owner = conflictStore.createTask("冲突对话", []), other = conflictStore.createTask("可删除对话", []);
  conflictStore.updateTask(owner.id, { status: "paused" });
  conflictStore.updateTask(other.id, { status: "paused" });
  const evidence = conflictStore.putRaw({ ...complete, id: randomUUID(), taskId: owner.id });
  conflictStore.addMessage(owner.id, "user", "冲突用户决定仍然需要保留");
  conflictStore.reportConflict(owner.id, { docIds: [], sourceIds: [evidence.id], oldClaim: "旧结论", newClaim: "新结论", reason: "需要用户裁决" });
  const protectedClear = conflictStore.clearHistory();
  assert.equal(protectedClear.deletedTasks, 1);
  assert.deepEqual(protectedClear.preservedTaskIds, [owner.id]);
  assert.equal(conflictStore.messages(owner.id).length, 1);
  assert.equal(conflictStore.conflicts().length, 1);
  console.log("PASS: independent batches; selected retries; cached recognition reuse; no transcript replay; completed and unselected inputs protected; unrelated draft retry rejected before mutation; history backup including draft Markdown; documents/versions/raw preserved; outside/junction/library session paths preserved; active-conflict owner preserved.");
} finally {
  conflictStore?.close();
  store.close();
  const resolved = realpathSync(root), relative = path.relative(realpathSync(verificationRoot), resolved);
  assert.ok(relative.startsWith("ingestion-verification-") && !relative.includes(path.sep));
  rmSync(resolved, { recursive: true, force: true });
}
