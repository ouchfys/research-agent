import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { projectRoot, qaRoot } from './workspace.mjs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { build } from 'esbuild';

const scratch = mkdtempSync(path.join(qaRoot, 'research-collection-identity-test-'));
const output = path.join(scratch, 'store.mjs');
await build({ entryPoints: [path.join(projectRoot, 'src/server/store.ts')], outfile: output, bundle: true, platform: 'node', format: 'esm', target: 'node22', logLevel: 'silent' });
const { Store } = await import(pathToFileURL(output).href);
let store;
const open = name => { store = new Store(path.join(scratch, name)); return store; };
const close = () => { store?.close(); store = undefined; };
const fixture = (title, categoryId = 'agent', extra = {}) => ({ categoryId, title, description: `${title}的方法、机制与适用条件。`, aliases: [], paperIds: [], sources: [], body: `# ${title}\n\n这是该主题的独立知识正文。`, expectedVersion: 0, ...extra });
const review = { materialUnderstanding: '已对照现有正文。', speculation: '事实与推测已区分。', conditions: '已说明适用条件。', methodIdentity: '独立主题与已有方法未混淆。', conflicts: '没有未处理知识冲突。', structure: '内容结构完整。', metadataConsistency: '标题简介正文一致。', passed: true, fixes: '' };
const passed = name => console.log(`PASS ${name}`);

try {
  open('collection');
  const identityA = store.saveManual(fixture('Method One', 'agent', { aliases: ['ＭＥＴＨＯＤ　ＯＮＥ'], paperIds: ['arXiv:2601.12345v1'] }));
  const identityB = store.saveManual(fixture('Separate Method', 'agent', { paperIds: ['https://arxiv.org/abs/2601.12345v3'] }));
  const unrelated = store.saveManual(fixture('不相关方法'));
  const cross = store.saveManual(fixture('Method One', 'infra'));
  const collection = store.createTask('日常收集', [cross.id]);
  assert.equal(collection.retrievalMode, 'collection');
  store.updateTask(collection.id, { status: 'paused' });
  store.markCategoriesRead(collection.id);
  assert.throws(() => store.scanCategoryBatch(collection.id, 'agent'), /不执行分类全量扫描/);
  assert.throws(() => store.scanPage(collection.id, 'agent', 1), /不执行分类全量扫描/);
  assert.throws(() => store.scanCollectionCategory(collection.id, 'agent', {}), /至少需要一个非空/);
  assert.throws(() => store.scanCollectionCategory(collection.id, 'agent', { title: '  ', aliases: [' '], paperIds: [''] }), /至少需要一个非空/);
  assert.equal(store.scans(collection.id).length, 0);
  let exact = store.scanCollectionCategory(collection.id, 'agent', { title: 'method one' });
  assert.equal(exact.scope, 'identity');
  assert(exact.note.includes('不代表整个分类'));
  assert.deepEqual(exact.documents.map(document => document.id), [identityA.id]);
  assert.throws(() => store.readCandidate(collection.id, unrelated.id), /精确标识候选/);
  assert.throws(() => store.putDraft(collection.id, { ...fixture(identityA.title), id: identityA.id, expectedVersion: identityA.version }), /重新读取/);
  store.readCandidate(collection.id, cross.id);
  exact = store.scanCollectionCategory(collection.id, 'agent', { paperIds: ['arxiv:2601.12345v9'] });
  assert.deepEqual(new Set(exact.documents.map(document => document.id)), new Set([identityA.id, identityB.id]));
  assert.throws(() => store.putDraft(collection.id, fixture('第三个独立方法', 'agent', { paperIds: ['arxiv:2601.12345'] })), /同一论文标识符还有未读/);
  store.readCandidate(collection.id, identityA.id);
  store.readCandidate(collection.id, identityB.id);
  const distinct = store.putDraft(collection.id, fixture('第三个独立方法', 'agent', { paperIds: ['arxiv:2601.12345'] }));
  const published = store.submitDraft(collection.id, distinct.draftId, distinct.revision, review).document;
  assert(published);
  assert.equal(store.documents('agent').length, 4);
  assert.equal(store.scans(collection.id).at(-1).scope, 'identity');
  assert.equal(store.scans(collection.id).at(-1).total, 3);
  assert(!store.scans(collection.id).at(-1).providedIds.includes(unrelated.id));
  assert.throws(() => store.putDraft(collection.id, fixture(identityA.title)), /同一标题或别名/);
  const oldDraft = store.putDraft(collection.id, { ...fixture(identityA.title), id: identityA.id, expectedVersion: identityA.version, aliases: identityA.aliases, paperIds: identityA.paperIds });
  writeFileSync(path.join(store.dataDir, 'library', `${identityA.id}.md`), '# Method One\n\n用户的外部最新修改。');
  assert.throws(() => store.submitDraft(collection.id, oldDraft.draftId, oldDraft.revision, review), /新版本|版本|扫描/);
  assert.equal(readFileSync(path.join(store.dataDir, 'library', `${identityA.id}.md`), 'utf8'), '# Method One\n\n用户的外部最新修改。');
  const unknownCategory = store.saveCategory({ name: '范围未确认目录' });
  const unknownTask = store.createTask('不能自动归入未确认范围', []);
  store.updateTask(unknownTask.id, { status: 'paused' });
  store.markCategoriesRead(unknownTask.id);
  assert.throws(() => store.scanCollectionCategory(unknownTask.id, unknownCategory.id, { title: '新资料' }), /范围尚未确认/);
  passed('日常任务仅提供精确身份候选、隔离分类、保留同论文独立方法与重名/最新版本守卫；自身发布不伪造全量扫描');
  close();

  open('legacy');
  const legacy = store.createTask('旧任务保持既有检索', [], 'maintenance');
  store.updateTask(legacy.id, { status: 'paused' });
  close();
  const db = new DatabaseSync(path.join(scratch, 'legacy', 'app.sqlite'));
  const storedTask = JSON.parse(db.prepare("SELECT value FROM records WHERE kind='task' AND id=?").get(legacy.id).value);
  delete storedTask.retrievalMode;
  db.prepare("UPDATE records SET value=? WHERE kind='task' AND id=?").run(JSON.stringify(storedTask), legacy.id);
  db.close();
  open('legacy');
  store.markCategoriesRead(legacy.id);
  assert.equal(store.scanCategoryBatch(legacy.id, 'agent').scope, 'category');
  assert.equal(store.scanCategoryBatch(legacy.id, 'agent').scan.complete, true);
  passed('缺少retrievalMode的旧任务继续使用原完整分类扫描');
  console.log('Collection identity and legacy retrieval checks passed.');
} finally {
  close();
  const resolved = path.resolve(scratch);
  if (!resolved.startsWith(qaRoot + path.sep) || !path.basename(resolved).startsWith('research-collection-identity-test-')) throw new Error('Refusing cleanup outside the isolated maintenance test directory.');
  if (existsSync(resolved)) rmSync(resolved, { recursive: true, force: true });
}
